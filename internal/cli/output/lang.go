// A Language is one entry of the language menu: the code stored in the settings file, the name
// shown in the menu, and the translations it selects.
type Language struct {
	Code string // Value kept in launcher.toml. Empty follows the system locale.
	Name string // Shown in the menu, written in the language itself.
	tag  language.Tag
	set  translations
}

// languages lists every language the launcher can print, in menu order. The first entry is the
// default: follow whatever the operating system asks for.
var languages = []Language{
	{Code: "", Name: "Follow system", set: en},
	{Code: "en", Name: "English", tag: language.English, set: en},
	{Code: "zh", Name: "简体中文", tag: language.Chinese, set: zh},
	{Code: "fr", Name: "Français", tag: language.French, set: fr},
	{Code: "ru", Name: "Русский", tag: language.Russian, set: ru},
	{Code: "es", Name: "Español", tag: language.Spanish, set: es},
	{Code: "de", Name: "Deutsch", tag: language.German, set: de},
}

var lang = en

// current is the code of the language in use, matching a Language.Code.
var current = ""

// systemTag is the language the operating system asked for, so that switching back to "follow
// system" does not need to detect it again.
var systemTag = language.English

// Languages returns every selectable language.
func Languages() []Language {
	return languages
}

// SetLang changes the language to the specified language, if translations for it exist. It is
// used at start-up, with the language the operating system reports.
func SetLang(tag language.Tag) {
	systemTag = tag
	applyCode("")
}

// SetLangCode applies the language stored in the settings file. A code that is not known, or the
// empty code, goes back to the system language. It reports the code that ended up in use.
func SetLangCode(code string) string {
	if !applyCode(code) {
		applyCode("")
	}
	return current
}

// CurrentLanguage returns the code of the language in use.
func CurrentLanguage() string {
	return current
}

// LanguageName returns the name shown in the menu for a code, marking the system language.
func LanguageName(code string) string {
	for _, candidate := range languages {
		if candidate.Code == code {
			if candidate.Code == "" {
				return Translate("shell.lang.system") + " (" + nameOf(systemTag) + ")"
			}
			return candidate.Name
		}
	}
	return Translate("shell.lang.system") + " (" + nameOf(systemTag) + ")"
}

// nameOf returns the menu name of the language matching a locale tag.
func nameOf(tag language.Tag) string {
	code := codeForTag(tag)
	for _, candidate := range languages {
		if candidate.Code == code {
			return candidate.Name
		}
	}
	return "English"
}

// applyCode switches to the translations of code, reporting whether the code was known. The empty
// code selects the language the operating system reports.
func applyCode(code string) bool {
	if code == "" {
		lang, current = translationsForTag(systemTag), ""
		return true
	}
	for _, candidate := range languages {
		if candidate.Code == code {
			lang, current = candidate.set, candidate.Code
			return true
		}
	}
	return false
}

// translationsForTag picks the translation set for a locale.
func translationsForTag(tag language.Tag) translations {
	code := codeForTag(tag)
	for _, candidate := range languages {
		if candidate.Code != "" && candidate.Code == code {
			return candidate.set
		}
	}
	return en
}

// codeForTag returns the code of the language a locale asks for, matching on the base language so
// that e.g. "de-AT" and "zh-Hans-CN" land on German and Chinese. It returns an empty code when the
// launcher has no translations for that language.
func codeForTag(tag language.Tag) string {
	base, _ := tag.Base()
	for _, candidate := range languages {
		if candidate.Code == "" {
			continue
		}
		if candidateBase, _ := candidate.tag.Base(); candidateBase == base {
			return candidate.Code
		}
	}
	return ""
}

// Translations returns the map of output translations for the current language.
func Translations() map[string]string {
	return lang
}

// Translate takes a translation string and looks up its human-readable text. If not available, it returns the same translation string.
func Translate(key string) string {
	t, ok := lang[key]
	if !ok {
		return key
	}
	return t
}
